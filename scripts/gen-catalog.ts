// Run: npm run catalog   (Node 22.18+ runs TypeScript directly)
// Writes catalog.json, COMPONENTS.md and AI-INDEX.md at the showcase root so people and AI tools can find components quickly.
import { writeFileSync, mkdirSync, readdirSync, readFileSync, existsSync } from "node:fs";
import { catalog, categories } from "../catalog/catalog.data.ts";

const root = new URL("../catalog/", import.meta.url);
const app = new URL("../../../apps/showcase/", import.meta.url);
// Entries point at files by path inside their package; make them repo-relative so an agent can open them.
// name -> source folder, found by scanning src/components/*/index.tsx and src/lib/*.ts
const src = new URL("../src/", import.meta.url);
const exportsOf = (text: string) => {
  const out: string[] = [];
  for (const m of text.matchAll(/^export\s+(?:declare\s+)?(?:async\s+)?(?:function|const|class|interface|type|enum|let)\s+(\w+)/gm)) out.push(m[1]);
  for (const m of text.matchAll(/^export\s*\{([^}]*)\}\s*;?/gm)) m[1].split(",").forEach((x) => out.push(x.trim().split(/\s+as\s+/).pop()!));
  return out.filter(Boolean);
};
const folders: { dir: string; file: string; exports: string[] }[] = readdirSync(new URL("components/", src)).sort().map((d) => {
  const file = `components/${d}/index.tsx`; return { dir: d, file, exports: exportsOf(readFileSync(new URL(file, src), "utf8")) };
});
const where = (f: string, names: string[] = []) => {
  if (f.startsWith("src/pages/")) return `apps/showcase/${f}`;
  const hit = folders.find((x) => names.some((n) => x.exports.includes(n)));
  return hit ? `packages/ui/src/${hit.file}` : `packages/ui/${f}`;
};
const w = (p: string, s: string) => writeFileSync(new URL(p, root), s);
mkdirSync(new URL("public/", app), { recursive: true });
w("catalog.json", JSON.stringify(catalog, null, 2));
writeFileSync(new URL("public/catalog.json", app), JSON.stringify(catalog));

let md = `# Component reference\n\nGenerated from \`catalog/catalog.data.ts\` (${catalog.length} entries). Do not edit by hand; run \`npm run catalog\`.\n\nImport everything from \`@bytesphere/ui\` (the barrel at \`src/components.ts\`).\n`;
for (const c of categories) {
  const items = catalog.filter((e) => e.category === c); if (!items.length) continue;
  md += `\n## ${c}\n`;
  for (const e of items) {
    md += `\n### ${e.name}\n\n${e.summary}\n\n- **File:** \`${where(e.file, e.exports)}\`\n- **Exports:** ${e.exports.map((x) => `\`${x}\``).join(", ")}\n`;
    if (e.variants?.length) md += `- **Variants:** ${e.variants.join(" · ")}\n`;
    if (e.props?.length) md += `- **Props:** ${e.props.map(([n, t, d]) => `\`${n}${t ? `: ${t}` : ""}\`${d ? ` (${d})` : ""}`).join("; ")}\n`;
    if (e.tokens?.length) md += `- **Tokens:** ${e.tokens.join(", ")}\n`;
    if (e.a11y) md += `- **Accessibility:** ${e.a11y}\n`;
    if (e.page) md += `- **Live example:** \`#/${e.page}\`\n`;
    md += `\n\`\`\`tsx\n${e.snippet}\n\`\`\`\n`;
  }
}
w("COMPONENTS.md", md);

let ai = `# AI index: find the component fast\n\nRead this first. Then open \`COMPONENTS.md\` (or \`catalog.json\`) for the entry you pick.\n\n## Rules\n1. Import from \`@bytesphere/ui\`. Do not copy markup from a page; compose these.\n2. Colors, radii, spacing come from tokens (Tailwind classes like \`bg-surface-raised\`, \`text-secondary\`, \`rounded-card\`). Never write hex.\n3. One primary button per view. Every async surface needs loading, empty, error and stale states (\`SkeletonKit\`, \`StatePanel\`).\n4. Use \`<Logo>\`; never type the company name in a font.\n5. Corner style, dark mode and navigation style are user choices set through \`useAppearance()\`; do not hardcode them.\n6. Glass, gradients and patterns only where their entry says so.\n\n## I need… → use\n\n| I need | Use | File |\n|---|---|---|\n`;
const rows: [string, string, string][] = [];
for (const e of catalog) for (const n of e.needs) rows.push([n, e.name, where(e.file, e.exports)]);
rows.sort((a, b) => a[0].localeCompare(b[0]));
ai += rows.map(([n, name, f]) => `| ${n} | ${name} | \`${f}\` |`).join("\n") + "\n";
w("AI-INDEX.md", ai);
console.log(`catalog: ${catalog.length} entries, ${rows.length} intents`);

// One README per component folder, so an agent that opens the folder sees what it is and how to use it.
let docs = 0, undocumented: string[] = [];
for (const f of folders) {
  const es = catalog.filter((e) => e.exports.some((n) => f.exports.includes(n)));
  let r = `<!-- Generated by \`npm run catalog\` from catalog/catalog.data.ts. Do not edit by hand. -->\n# ${f.dir}\n\nExports: ${f.exports.map((x) => `\`${x}\``).join(", ")}\n\nSource: \`index.tsx\` in this folder. Import: \`import { ${f.exports.filter((x) => /^[A-Z]/.test(x)).slice(0, 3).join(", ") || f.exports[0]} } from "@bytesphere/ui"\`\n`;
  if (!es.length) undocumented.push(f.dir);
  for (const e of es) {
    r += `\n## ${e.name}\n\n${e.summary}\n\nUse when: ${e.needs.slice(0, 6).join("; ")}.\n`;
    if (e.variants?.length) r += `\n- **Variants:** ${e.variants.join(" · ")}\n`;
    if (e.props?.length) r += `- **Props:** ${e.props.map(([n, t, d]) => `\`${n}${t ? `: ${t}` : ""}\`${d ? ` (${d})` : ""}`).join("; ")}\n`;
    if (e.tokens?.length) r += `- **Tokens:** ${e.tokens.join(", ")}\n`;
    if (e.a11y) r += `- **Accessibility:** ${e.a11y}\n`;
    if (e.page) r += `- **Live example:** \`#/${e.page}\` in the showcase\n`;
    r += `\n\`\`\`tsx\n${e.snippet}\n\`\`\`\n`;
  }
  if (!es.length) r += `\nNo catalog entry yet. Add one in \`catalog/catalog.data.ts\`, then run \`npm run catalog\`.\n`;
  writeFileSync(new URL(`components/${f.dir}/README.md`, src), r); docs++;
}
console.log(`component folders: ${folders.length}, READMEs: ${docs}, without catalog entry: ${undocumented.length}`);
if (process.env.LIST_UNDOCUMENTED) console.log(undocumented.join(" "));

// Keep the public barrel in sync with the folders, so adding a component folder is enough to export it.
const libFiles = readdirSync(new URL("lib/", src)).filter((f) => /\.tsx?$/.test(f) && f !== "mark.ts").map((f) => f.replace(/\.tsx?$/, "")).sort();
const reexports = ["Check", "Minus", "QrCode"]; // lucide icons the components used to re-export; kept for compatibility
let barrel = `/** Public API of @bytesphere/ui. Import every reusable component from "@bytesphere/ui".\n *  Generated by \`npm run catalog\` from the folders in src/components and src/lib; do not edit by hand.\n *  Lookup: AGENTS.md → catalog/AI-INDEX.md → catalog/COMPONENTS.md. */\n`;
barrel += libFiles.map((f) => `export * from "./lib/${f}";`).join("\n") + "\n";
barrel += reexports.map((n) => `export { ${n} } from "lucide-react";`).join("\n") + "\n";
barrel += folders.map((f) => `export * from "./components/${f.dir}";`).join("\n") + "\n";
writeFileSync(new URL("index.ts", src), barrel);
